CREATE TABLE ROL (
    ID_ROL      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE      VARCHAR2(30 CHAR)  NOT NULL,
    DESCRIPCION VARCHAR2(200 CHAR),
    CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE USUARIO (
    ID_USUARIO      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOMBRE_USUARIO  VARCHAR2(30 CHAR)  NOT NULL,
    CORREO          VARCHAR2(120 CHAR) NOT NULL,
    CLAVE_HASH      VARCHAR2(100 CHAR) NOT NULL,
    NOMBRE_COMPLETO VARCHAR2(100 CHAR) NOT NULL,
    ACTIVO          NUMBER(1) DEFAULT 1 NOT NULL,
    FECHA_REGISTRO  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ID_ROL          NUMBER(19) NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_NOMBRE UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_ACTIVO CHECK (ACTIVO IN (0, 1)),
    CONSTRAINT FK_USUARIO_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL (ID_ROL)
);

